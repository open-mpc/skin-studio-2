// ---- Python-compatible value model & JSON dumper ------------------------------------------------

// A JSON object as an ordered list of [key, value] pairs. Keys may repeat (mirrors gen_ui's Obj).
export class Obj {
  constructor(public pairs: [string, Val][]) {}
}
function obj(...pairs: [string, Val][]): Obj {
  return new Obj(pairs);
}
// Marks a value that must render as a Python float (e.g. 30.0), vs a plain int.
class Flt {
  constructor(public v: number) {}
}
type Val = Obj | Flt | Val[] | string | number | boolean | null;

// Python repr() of a float. Our values are all integer-valued floats (30.0, 4.0 ...); handle the
// general case defensively with a shortest round-trip fallback.
function reprFloat(v: number): string {
  if (Number.isInteger(v)) return `${v}.0`;
  return String(v);
}

// Pretty-print like json.dumps(indent=4) but accepting Obj (ordered, duplicate keys).
export function dumpJson(value: Val, indent = 0): string {
  const pad = " ".repeat(indent);
  const innerPad = " ".repeat(indent + 4);
  if (value instanceof Obj) {
    if (value.pairs.length === 0) return "{}";
    const parts = value.pairs.map(
      ([k, v]) => innerPad + JSON.stringify(String(k)) + ": " + dumpJson(v, indent + 4)
    );
    return "{\n" + parts.join(",\n") + "\n" + pad + "}";
  }
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    const parts = value.map((v) => innerPad + dumpJson(v, indent + 4));
    return "[\n" + parts.join(",\n") + "\n" + pad + "]";
  }
  if (typeof value === "boolean") return value ? "true" : "false";
  if (value === null) return "null";
  if (value instanceof Flt) return reprFloat(value.v);
  if (typeof value === "number") return String(value); // ints
  return JSON.stringify(value); // string
}

// ---- Errors -------------------------------------------------------------------------------------
export class UiError extends Error {}

function fail(where: string | null, msg: string, ...hints: string[]): never {
  let text = where ? `ERROR in ${where}: ${msg}` : "ERROR: " + msg;
  for (const h of hints) if (h) text += "\n  " + h;
  throw new UiError(text);
}

// ---- params.json --------------------------------------------------------------------------------
class Param {
  constructor(
    public index: number,
    public name: string,
    public kind: string,
    public choices: string[] | null,
    public default_: number | null = null,
    public display = ""
  ) {}

  get looksBipolar(): boolean {
    if (this.isDiscrete || typeof this.default_ !== "number") return false;
    return Math.abs(this.default_ - 0.5) <= 0.01 && BIPOLAR_ZERO_RE.test(this.display.trim());
  }
  get handle(): string {
    return `Parameter ${this.index}`;
  }
  get isDiscrete(): boolean {
    return this.kind === "choice" || this.kind === "bool";
  }
}

function isPlainObject(x: unknown): x is Record<string, unknown> {
  return typeof x === "object" && x !== null && !Array.isArray(x);
}
function isInt(x: unknown): x is number {
  return typeof x === "number" && Number.isInteger(x);
}

function loadParams(data: unknown, path = "params.json"): Param[] {
  if (!isPlainObject(data) || !Array.isArray((data as any).params))
    fail(path, 'expected an object with a "params" array (as written by host_sim dump).');
  const arr = (data as any).params as unknown[];
  const params: Param[] = [];
  for (let i = 0; i < arr.length; i++) {
    const p = arr[i];
    if (!isPlainObject(p) || !("name" in p)) fail(path, `params[${i}] is not an object with a "name"`);
    const po = p as Record<string, unknown>;
    let index = po.index === undefined ? i : po.index;
    if (!isInt(index)) fail(path, `params[${i}].index must be an integer`);
    const kind = (po.kind as string) || "float";
    let choices = po.choices as unknown;
    if (kind === "bool") {
      if (!(Array.isArray(choices) && choices.length === 2)) choices = ["Off", "On"];
    } else if (kind === "choice") {
      if (!(Array.isArray(choices) && choices.length >= 1))
        fail(path, `params[${i}] ("${po.name}") has kind "choice" but no "choices" list`);
    } else {
      choices = null;
    }
    const d = po.default;
    const default_ = typeof d === "number" && !(typeof d === "boolean") ? d : null;
    params.push(
      new Param(
        index as number,
        String(po.name),
        kind,
        choices ? (choices as unknown[]).map((c) => String(c)) : null,
        default_,
        String(po.display ?? "")
      )
    );
  }
  if (params.length === 0)
    fail(
      path,
      "the plugin reports no parameters; there is nothing to lay out.",
      "Add parameters with addParam() in the plugin source, or use --no-ui in build.py."
    );
  return params;
}

class ParamTable {
  byName = new Map<string, Param>();
  byLower = new Map<string, Param>();
  constructor(public params: Param[]) {
    for (const p of params) {
      if (!this.byName.has(p.name)) this.byName.set(p.name, p);
      if (!this.byLower.has(p.name.toLowerCase())) this.byLower.set(p.name.toLowerCase(), p);
    }
  }
  lookup(name: unknown, where: string): Param {
    if (typeof name !== "string")
      fail(where, `"param" must be a parameter name (a string), got ${JSON.stringify(name)}`);
    let p = this.byName.get(name as string);
    if (p === undefined) p = this.byLower.get((name as string).toLowerCase());
    if (p === undefined) {
      const names = this.params.map((q) => q.name);
      fail(
        where,
        `unknown parameter "${name}".`,
        "Available parameter names (from params.json): " + names.map((n) => `"${n}"`).join(", ")
      );
    }
    return p;
  }
}

