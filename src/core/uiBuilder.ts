// Per-control text sizes: rewrite the Name/Value label children of a built component (0 removes the label).
function retext(comp: Obj, ns: number | null, vs: number | null): Obj {
  const get = (o: Obj, k: string): Val | undefined => o.pairs.find((p) => p[0] === k)?.[1];
  const kids = get(comp, "componentsData");
  if (!Array.isArray(kids)) return comp;
  const keep: Val[] = [];
  for (const e of kids) {
    const cd = e instanceof Obj ? get(e, "componentData") : undefined;
    const data = cd instanceof Obj ? get(cd, "data") : undefined;
    const isLabel = cd instanceof Obj && get(cd, "type") === "Label" && data instanceof Obj;
    const kind = isLabel ? get(data as Obj, "type") : null;
    const want = kind === "Name" ? ns : kind === "Value" ? vs : null;
    if (want === null) { keep.push(e); continue; }
    if (want === 0) continue;
    const ts = get(data as Obj, "textStyle");
    const font = ts instanceof Obj ? get(ts, "font") : undefined;
    if (font instanceof Obj) { const h = font.pairs.find((p) => p[0] === "height"); if (h) h[1] = new Flt(want); }
    keep.push(e);
  }
  const cp = comp.pairs.find((p) => p[0] === "componentsData");
  if (cp) cp[1] = keep;
  return comp;
}
