// repeat strip: a version-3 component (ui-reference §4.6) laid out `count` times; the child binds to
// Parameter {Increment:Base=<baseIndex>} so copy r reads base+r — a step row / result grid. The base is
// baked into the handle, so the tab entry needs no remap.
//
// HARDWARE-VERIFIED (MPC Force 3.9.1, 2026-11-10): `repeats` expands ONLY on a tab's ROOT component
// (ui-reference §3.5). The same strip referenced by `type` from a grid slot renders nothing. So a repeat
// strip is a page of its own: tabComponent returns this component as the tab root, and the page may hold
// nothing else (the root repeats all of its children).
function repeatStripComponent(style: Style, baseIndex: number, count: number): Obj {
  const childW = Math.max(1, Math.floor(1240 / count)); // full tab width / count
  const childH = 620;
  const child = obj(
    ["version", 2],
    ["componentData", obj(["version", 1], ["name", "step"], ["type", "Slider"],
      // Track must contrast with the page background or the empty bars are invisible; use a mid grey
      // (not style.background). valueColour is the accent fill.
      ["data", obj(["version", 2], ["sliderType", "ColourBar"], ["direction", "Vertical"],
        ["backgroundColour", "ff3a3a3d"], ["outlineColour", style.muted], ["valueColour", style.accent],
        ["isBipolar", false], ["handleName", "Data"])])],
    ["handle remapping", obj(["version", 1], ["map", [obj(["key", "Data"], ["value", `Parameter {Increment:Base=${baseIndex}}`])]])],
    ["bounds", obj(["version", 1], ["acceptsHWFocus", "Yes"], ["showWhenDataModelInvalid", "Hide"],
      ["whenVisible", "Always"], ["boundsType", "Absolute"], ["bounds", `0 0 ${childW} ${SLOT_H}`])]
  );
  return obj(
    ["version", 3],
    ["actions", []],
    ["backgroundData", backgroundData("00000000")],
    ["ignoreMousePresses", false],
    ["disableCoarseDataWheel", false],
    ["repeats", count],
    ["componentsData", [child]]
  );
}

// ---- Assembling the two files -------------------------------------------------------------------
function tabComponent(page: Page, style: Style, custom: KitAssets = {}): Obj {
  const rep = page.controls.find((c) => c.full === "repeat");
  if (rep) {
    if (page.controls.length !== 1) fail(null, `page "${page.name}": a repeat strip must be the only control on its page (repeats expand only on the tab root)`);
    return repeatStripComponent(style, rep.param!.index, rep.repeatCount);
  }
  const children: Val[] = [];
  const imageEntry = (nm: string, im: { asset: string; visible?: [Param, number]; valuePic?: Param }, b: string) => {
    const a = custom[im.asset];
    if (!a) fail(null, `page "${page.name}" references image asset "${im.asset}" which is not in the project`);
    const inv = im.visible ? [`IndexedEnabling/${im.visible[1]}/${im.visible[0].choices!.length}/${im.visible[0].handle}`] : null;
    if (im.valuePic) {
      if (a![1] < 2) fail(null, `page "${page.name}": value picture "${im.asset}" must be a filmstrip of two or more frames`);
      children.push(entry(nm, "Image", obj(["version", 2], ["imageType", "FilmStrip"], ["colour", "0"], ["image", a![0]], ["numFrames", a![1]], ["handleName", "Data"]), b, "No", "Show", "Always",
        [["Data", im.valuePic.handle]], inv));
      return;
    }
    children.push(entry(nm, "Image", obj(["version", 2], ["imageType", "Regular"], ["colour", "0"], ["image", a![0]]), b, "No", "Show", "Always", [], inv));
  };
  if (page.background) imageEntry("background", { asset: page.background }, "0 0 1280 628");
  page.images.forEach((im, k) => imageEntry(`image ${k + 1}`, im, `${im.x} ${im.y} ${im.w} ${im.h}`));
  page.controls.forEach((ctl, i) => {
    const row = Math.floor(i / 4);
    const col = i % 4;
    const bounds = ctl.bounds ? ctl.bounds.join(" ") : `${SLOT_X[col]} ${SLOT_Y[row]} ${SLOT_W} ${SLOT_H}`;
    const ox = ctl.bounds ? ctl.bounds[0] : SLOT_X[col];
    const oy = ctl.bounds ? ctl.bounds[1] : SLOT_Y[row];
    let invalidating: string[] | null = null;
    if (ctl.visible) {
      const [vp, idx] = ctl.visible;
      invalidating = [`IndexedEnabling/${idx}/${vp.choices!.length}/${vp.handle}`];
    }
    if (ctl.widget === "empty") return;
    if (ctl.widget === "text") {
      children.push(
        entry("text " + i, "Label", labelData("Text", style.text, 30.0, "left", ctl.text), bounds, "No", "Show", "Always", [], invalidating)
      );
      return;
    }
    // Full-TUI extension controls: momentary button (focusable, ResetOnGestureEnd) and readout (not
    // focusable, no Q-Link). ResetOnGestureEnd rides on the same additionalInvalidatingHandles list
    // that visibleWhen uses (ui-reference §"handles").
    if (ctl.full === "button") {
      const inv = [...(invalidating ?? []), `ResetOnGestureEnd/${ctl.param!.handle}`];
      children.push(
        entry(ctl.param!.name, "momentaryButton", obj(["version", 1], ["handleName", "Data"]), bounds, "Yes", "Hide", "Always",
          [["Data", ctl.param!.handle]], inv)
      );
      return;
    }
    if (ctl.full === "readout") {
      children.push(
        entry(ctl.param!.name, "readout", obj(["version", 1], ["handleName", "Data"]), bounds, "No", "Hide", "Always",
          [["Data", ctl.param!.handle]], invalidating)
      );
      return;
    }
    if (ctl.full === "meter") {
      // A level meter drawn from two pictures sized to the control (ui-reference §6.15, "less tested"). The MPC has
      // no audio feed for a VST, so the plugin writes its level into the parameter this binds to.
      const [mw, mh] = ctl.bounds ? [ctl.bounds[2], ctl.bounds[3]] : [SLOT_W, SLOT_H];
      const nm = meterAssetNames(mw, mh);
      const off = custom[nm.off], on = custom[nm.on];
      if (!off || !on) fail(null, `page "${page.name}": the pictures for meter "${ctl.param!.name}" were not generated`);
      const h = ctl.param!.handle;
      children.push(entry(ctl.param!.name, "Meter",
        obj(["version", 3], ["direction", ctl.meterDir], ["invert", false], ["inactiveImage", off![0]], ["peakImage", on![0]], ["rmsImage", on![0]],
          ["peakHandle", h], ["rmsHandle", h], ["peakHoldHandle", `Hold/${h}`], ["peakHoldSize", 10], ["peakHoldColour", "ffffffff"]),
        bounds, "No", "Hide", "Always", [], invalidating));
      return;
    }
    if (ctl.full === "repeat") {
      // No remap — the child's {Increment:Base} handle already resolves to the bound parameters.
      children.push(entry(ctl.param!.name, ctl.definition, obj(["version", 1], ["handleName", "Data"]), bounds, "Yes", "Hide", "Always", [], invalidating));
      return;
    }
    children.push(
      entry(ctl.param!.name, ctl.definition, obj(["version", 1], ["handleName", "Data"]), bounds, "Yes", "Hide", "Always", [
        ["Data", ctl.param!.handle],
      ], invalidating)
    );
    if (ctl.definition.startsWith("radio")) {
      const [width, xs] = SEGMENTS[ctl.param!.choices!.length];
      ctl.param!.choices!.forEach((choice, ci) => {
        const x = xs[ci];
        children.push(
          entry(
            `${ctl.param!.name} seg ${ci}`,
            "Label",
            labelData("Text", style.text, 22.0, "horizontallyCentred verticallyCentred", choice),
            `${ox + x} ${oy + 54} ${width} 40`,
            "No",
            "Hide",
            "Always",
            [],
            invalidating
          )
        );
      });
    }
  });
  return componentDefinition([], children, style.background);
}

function buildTui(pages: Page[], params: Param[], style: Style, knobImage: string | null, frames: number, kitAssets: KitAssets, custom: KitAssets = {}): Obj {
  const used: string[] = [];
  for (const page of pages)
    for (const ctl of page.controls)
      if (ctl.param !== null && !used.includes(ctl.definition)) used.push(ctl.definition);
  if (!used.includes("sliderWithFocus")) used.unshift("sliderWithFocus");

  const kit = (name: string): [string, number, [number, number]] => {
    if (!(name in kitAssets))
      fail(null, `the UI kit has no asset ${name} (tools/make_ui_kit.py --list shows them)`);
    return kitAssets[name];
  };

  const defs: [string, Obj][] = [];
  for (const fullName0 of used) {
    const tm = /~n(\d*)v(\d*)$/.exec(fullName0);
    const nsz = tm && tm[1] !== "" ? parseInt(tm[1], 10) : null;
    const vsz = tm && tm[2] !== "" ? parseInt(tm[2], 10) : null;
    const fullName = tm ? fullName0.slice(0, -tm[0].length) : fullName0;
    const szm = /@(\d+)$/.exec(fullName);
    const knobSize = szm ? parseInt(szm[1], 10) : null;
    const name = szm ? fullName.slice(0, -szm[0].length) : fullName;
    const sm = /^(knob|fader)Strip:(Uni|Bi):(.+)$/.exec(name);
    if (sm) {
      const a = custom[sm[3]];
      if (!a) fail(null, `control references image asset "${sm[3]}" which is not in the project`);
      const bi = sm[2] === "Bi";
      const overlay = bi ? "knob overlay bipolar" : "knob overlay";
      const sc = sm[1] === "knob"
        ? knobComponent(style, overlay, [a[0], a[1], knobSize ?? Math.min(a[2][0], a[2][1])], a[1], bi)
        : faderComponent(style, overlay, a[0], a[1]);
      defs.push([fullName0, tm ? retext(sc, nsz, vsz) : sc]);
      continue;
    }
    const menu = name.endsWith("Menu");
    const overlay = menu ? "menu overlay" : name.includes("Bi") ? "knob overlay bipolar" : "knob overlay";
    const base = menu ? name.slice(0, -4) : name;
    let comp: Obj;
    if (base === "sliderWithFocus") {
      comp = sliderComponent(style, overlay);
    } else if (base === "knobUni" || base === "knobBi") {
      if (knobImage) {
        comp = knobComponent(style, overlay, [knobImage, frames, 77], frames, base === "knobBi");
      } else if (Object.keys(kitAssets).length) {
        const [f, n, size] = kit(base === "knobUni" ? "knob_uni" : "knob_bi");
        comp = knobComponent(style, overlay, [f, n, knobSize ?? size[0]], n, base === "knobBi");
      } else {
        comp = knobComponent(style, overlay, null, frames, base === "knobBi");
      }
    } else if (base === "faderUni" || base === "faderBi") {
      const [f, n] = kit(base === "faderUni" ? "fader_h_uni" : "fader_h_bi");
      comp = faderComponent(style, overlay, f, n);
    } else if (base === "toggle") {
      kit("toggle_on");
      kit("toggle_off");
      comp = toggleComponent(style, overlay);
    } else if (base.startsWith("radio")) {
      const n = parseInt(base.slice(5), 10);
      kit(`seg${n}_on`);
      kit(`seg${n}_off`);
      comp = radioComponent(style, overlay, n);
    } else if (base === "momentaryButton") {
      kit("button_on");
      kit("button_off");
      comp = momentaryButtonComponent(style, "knob overlay");
    } else if (base === "readout") {
      comp = readoutComponent(style);
    } else if (base === "stepper") {
      comp = stepperComponent(style, "numeric overlay");
    } else if (base === "meter") {
      continue; // a Meter is a built-in widget placed directly in the tab, not a referenced definition
    } else if (base.startsWith("repeat ")) {
      continue; // emitted as the tab root by tabComponent, not a referenced definition
    } else {
      fail(null, `internal error: no builder for component ${name}`);
    }
    defs.push([fullName0, tm ? retext(comp, nsz, vsz) : comp]);
  }
  defs.push(["knob overlay", overlayComponent("KnobOverlay", knobOverlayData(false), style.background)]);
  defs.push(["knob overlay bipolar", overlayComponent("KnobOverlay", knobOverlayData(true), style.background)]);
  defs.push(["menu overlay", overlayComponent("MenuOverlay", menuOverlayData(), style.background)]);
  // NumericOverlay is an EXTENSION overlay — only appended when a stepper uses it, so the base builder's
  // output (which never has a stepper) stays byte-identical to gen_ui.
  if (used.includes("stepper"))
    defs.push(["numeric overlay", overlayComponent("NumericOverlay", numericOverlayData(), style.background)]);

  // replacementStrings: every discrete parameter referenced by a control or a visibleWhen.
  const referenced = new Map<number, Param>();
  for (const page of pages)
    for (const ctl of page.controls) {
      if (ctl.param !== null) referenced.set(ctl.param.index, ctl.param);
      if (ctl.visible) referenced.set(ctl.visible[0].index, ctl.visible[0]);
    }
  for (const page of pages)
    for (const im of page.images) {
      if (im.visible) referenced.set(im.visible[0].index, im.visible[0]);
      if (im.valuePic) referenced.set(im.valuePic.index, im.valuePic);
    }
  const replacements = [...referenced.entries()]
    .sort((a, b) => a[0] - b[0])
    .filter(([, p]) => p.isDiscrete)
    .map(([, p]) => obj(["key", p.handle], ["value", p.choices!.slice() as Val[]]));

  const tabs: Val[] = [];
  pages.forEach((page, ti) => {
    tabs.push(
      obj(
        ["version", 1],
        ["tabName", page.name],
        ["fnKeyIndex", ti],
        ["fnKeySubIndex", 0],
        ["componentDefinition", tabComponent(page, style, custom)],
        ["qlinkBoundsData", qlinkBoundsFor(page)]
      )
    );
  });

  const pageData = obj(
    ["version", 1],
    [
      "componentDefinitions",
      obj(["version", 2], ["importFiles", []], ["localComponentDefinitions", defs.map(([k, v]) => obj(["key", k], ["value", v]))]),
    ],
    ["replacementStrings", replacements],
    ["info", obj(["version", 1], ["type", "CompleteDescription"])],
    ["tabs", tabs]
  );
  return obj(["pageData", pageData]);
}


// ---- Free-form Q-Link support ---------------------------------------------------------------------
// Physical numbering (ui-reference §8.2): bank c (Bank Direction "Column") = Q-Links 13+c, 9+c, 5+c, 1+c.
const BANK_ORDER = [13, 9, 5, 1, 14, 10, 6, 2, 15, 11, 7, 3, 16, 12, 8, 4];
function isQlinkControl(c: Control): boolean {
  return c.param !== null && c.full !== "readout" && c.full !== "meter" && c.widget !== "text" && c.widget !== "empty";
}
/** Q-Link number (1-16) → parameter index, for a free-form page. Explicit `qlinks`, else the Akai default
 *  column-major order over the page's bindable controls. */
function freeQlinkAssignment(page: Page, params: Param[]): Map<number, number> {
  const out = new Map<number, number>();
  if (page.qlinks) {
    page.qlinks.slice(0, 16).forEach((name, k) => {
      if (name === null || name === undefined) return;
      const p = params.find((q) => q.name === name);
      if (!p) fail(null, `page "${page.name}": qlinks names unknown parameter "${name}"`);
      out.set(k + 1, p!.index);
    });
    return out;
  }
  const seen = new Set<number>();
  let n = 0;
  for (const c of page.controls) {
    if (!isQlinkControl(c) || seen.has(c.param!.index) || n >= 16) continue;
    seen.add(c.param!.index);
    out.set(BANK_ORDER[n++], c.param!.index);
  }
  return out;
}
function ctlRect(page: Page, i: number): [number, number, number, number] {
  const c = page.controls[i];
  return c.bounds ?? [SLOT_X[i % 4], SLOT_Y[Math.floor(i / 4)], SLOT_W, SLOT_H];
}
/** Focus rectangles: explicit, else one per bank = the padded union of the controls its Q-Links drive. */
function qlinkBoundsFor(page: Page): Val[] {
  if (!page.free) return QLINK_BOUNDS.slice();
  if (page.qlinkBounds) return page.qlinkBounds.slice();
  const params: Param[] = [];
  const byParam = new Map<number, number>(); // param index → control index
  page.controls.forEach((c, i) => { if (isQlinkControl(c) && !byParam.has(c.param!.index)) { byParam.set(c.param!.index, i); params.push(c.param!); } });
  const assign = page.qlinks ? null : freeQlinkAssignment(page, params);
  const rects: Val[] = [];
  for (let bank = 0; bank < 4; bank++) {
    let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
    for (let r = 0; r < 4; r++) {
      const q = BANK_ORDER[bank * 4 + r];
      const pi = assign ? assign.get(q) : undefined;
      if (pi === undefined) continue;
      const ci = byParam.get(pi);
      if (ci === undefined) continue;
      const [x, y, w, h] = ctlRect(page, ci);
      x0 = Math.min(x0, x); y0 = Math.min(y0, y); x1 = Math.max(x1, x + w); y1 = Math.max(y1, y + h);
    }
    if (x0 < 1e9) {
      const pad = 12;
      const X = Math.max(0, x0 - pad), Y = Math.max(0, y0 - pad);
      rects.push(`${X} ${Y} ${Math.min(1280, x1 + pad) - X} ${Math.min(628, y1 + pad) - Y}`);
    }
  }
  return rects;
}

function buildQlinks(pages: Page[], params: Param[]): Obj {
  const entries: Val[] = [];
  pages.forEach((page, ti) => {
    const assigned = new Map<number, number>();
    if (page.free) {
      freeQlinkAssignment(page, params).forEach((pi, q) => assigned.set(q, pi));
    } else
    page.controls.forEach((ctl, i) => {
      // A readout is not focusable and takes no Q-Link; everything else bound does.
      if (ctl.param !== null && ctl.full !== "readout") {
        const row = Math.floor(i / 4);
        const col = i % 4;
        assigned.set(slotQlink(row, col), ctl.param.index);
      }
    });
    const qmap = new Obj(
      Array.from({ length: 16 }, (_, k) => {
        const q = k + 1;
        return ["Q-Link " + q, assigned.has(q) ? assigned.get(q)! : -1] as [string, Val];
      })
    );
    entries.push(obj(["Tab", ti + 1], ["SubTab", 1], ["Bank Direction", "Column"], ["Q-Links", qmap]));
  });
  const indices = params.map((p) => p.index).sort((a, b) => a - b);
  const first16 = indices.slice(0, 16);
  const program = new Obj(
    Array.from({ length: 16 }, (_, q) => ["Q-Link " + (q + 1), q < first16.length ? first16[q] : -1] as [string, Val])
  );
  return obj(
    ["version", 4],
    ["info", obj(["version", 1], ["type", "CompleteDescription"])],
    ["Screen Mode Q-Links", obj(["version", 4], ["map", entries])],
    ["Program Mode Q-Links", program]
  );
}

// ---- Public entry -------------------------------------------------------------------------------
export type GenerateResult = { tui: string; qlinks: string; kit: KitInfo | null };

/**
 * Faithful port of gen_ui.generate's file production. Returns the two files' exact text (with the
 * trailing newline gen_ui writes). `resolveKitAssets` stands in for kit_dir_for: given the resolved
 * KitInfo it returns the kit's asset manifest (produced separately by the uiKit module). It is only
 * called when a kit is in play, mirroring gen_ui (kit_assets = {} otherwise).
 */
export function generate(
  paramsData: unknown,
  uiData: unknown | null,
  resolveKitAssets: (kit: KitInfo) => KitAssets,
  customAssets: KitAssets = {} // user assets: name → [file, frames, [frameW, frameH]]
): GenerateResult {
  const params = loadParams(paramsData);
  const table = new ParamTable(params);
  let pages: Page[], style: Style, knobImage: string | null, frames: number, kit: KitInfo | null;
  if (uiData) {
    ({ pages, style, knobImage, frames, kit } = loadUi(uiData, table));
  } else {
    pages = autoPages(params);
    style = { ...DEFAULT_STYLE };
    knobImage = null;
    frames = 127;
    kit = null;
  }
  const kitAssets: KitAssets = kit ? resolveKitAssets(kit) : {};
  const tui = buildTui(pages, params, style, knobImage, frames, kitAssets);
  const qlinks = buildQlinks(pages, params);
  return { tui: dumpJson(tui) + "\n", qlinks: dumpJson(qlinks) + "\n", kit };
}

// A pre-parsed control spec — the auto-layout EXTENSION path into the builder. Unlike `generate`
// (which parses ui.json), this takes controls already decided by the packer, including the full-TUI
// widgets ui.json cannot express. Simple widgets behave exactly as the ui.json path.
export interface ControlSpec {
  empty?: boolean;
  text?: string;
  param?: string; // parameter name
  widget?: string; // simple widget: slider|knob|fader|switch; ignored for full/text/empty
  overlay?: "knob" | "menu";
  polarity?: "auto" | "unipolar" | "bipolar";
  visibleWhen?: { param: string; choice?: string; index?: number };
  full?: FullKind; // "button" | "readout" | "stepper" | "repeat"
  repeatCount?: number; // for full === "repeat": consecutive params the strip binds (>= 2)
  bounds?: [number, number, number, number]; // free-form position/size (x y w h) instead of the grid slot
  nameSize?: number; // name text size in px (8-60); 0 hides the name (knob/fader/slider)
  valueSize?: number; // value text size in px (8-60); 0 hides the value
  size?: number; // knob picture size in px (24-107); scales the filmstrip within its box
  strip?: string; // knob/fader: custom filmstrip asset name (a look or an uploaded image)
  meterDir?: "Up" | "Down" | "Left" | "Right"; // full === "meter": the direction the bar fills (default Up)
}
export interface PlacedImage {
  asset: string; x: number; y: number; w: number; h: number;
  when?: { param: string; index: number }; // show only while this choice parameter is on option `index` (mode artwork)
  param?: string; // value picture: the asset is a vertical filmstrip whose frame follows this parameter
}
/** Artwork drawn only while choice parameter `param` is on option `index` (v1's `art when=`). */
export interface ArtMode { param: string; index: number; svg: string; asset?: string }
export interface PageSpec {
  name: string;
  controls: ControlSpec[];
  qlinks?: (string | null)[]; // explicit Q-Link k+1 → parameter name
  qlinkBounds?: string[]; // explicit Q-Link focus rectangles ("x y w h")
  background?: string; // asset name: full-tab background image
  images?: PlacedImage[]; // placed images (logos, panels, mode artwork, value pictures)
  art?: { svg: string; asset?: string; modes?: ArtMode[] }; // EDITOR-ONLY: SVG source of artwork drawn in Inkscape (ignored by the builder; `asset` is its rendered full-tab image; `modes` = artwork that shows in one mode of a choice parameter only)
}

const KIT_OR_FULL = new Set([...KIT_WIDGETS, "button"]); // widgets/fulls that pull in the kit

/**
 * Build TUI.json + Q-Links.json from pre-decided controls (the auto-layout path). Mirrors the tail of
 * loadUi (kit selection, defaults) without re-parsing JSON. EXTENSION — the full-TUI widgets are NOT
 * hardware-verified; see the plan's full-TUI gate.
 */
export function generateFromControls(
  paramsData: unknown,
  pageSpecs: PageSpec[],
  resolveKitAssets: (kit: KitInfo) => KitAssets,
  customAssets: KitAssets = {}, // user assets: name → [file, frames, [frameW, frameH]]
  styleOverride: Partial<Style> = {} // page colours (aarrggbb): background, accent, text, muted
): GenerateResult {
  const params = loadParams(paramsData);
  const table = new ParamTable(params);
  const style: Style = { ...DEFAULT_STYLE, ...styleOverride };

  const pages: Page[] = pageSpecs.map((ps, pi) => {
    const controls = ps.controls.map((c, ci) => {
      const ctl = makeControl(c, ci);
      if (c.bounds && !c.empty) {
        if (c.bounds.length !== 4 || c.bounds.some((n) => !Number.isFinite(n))) fail(`page[${pi}].controls[${ci}]`, "bounds must be [x, y, w, h]");
        ctl.bounds = c.bounds.map((n) => Math.round(n)) as [number, number, number, number];
      }
      return ctl;
    });
    function makeControl(c: ControlSpec, ci: number): Control {
      const where = `page[${pi}].controls[${ci}]`;
      if (c.empty) return new Control("empty");
      if (c.text !== undefined) return new Control("text", null, c.text);
      if (c.param === undefined) fail(where, 'control needs a "param"');
      const param = table.lookup(c.param, where);
      const visible = c.visibleWhen ? parseVisibleWhen(c.visibleWhen, table, where) : null;
      if (c.full) {
        // Neutral widget strings so tabComponent's "text"/"empty" branches don't catch these; the
        // full-TUI branch (checked by ctl.full) handles them. "button" pulls in the kit (see usesKit).
        const neutral = c.full === "button" ? "switch" : c.full; // "readout" | "stepper" | "repeat" | "meter"
        const ctl = new Control(neutral, param, null, visible);
        ctl.full = c.full;
        if (c.full === "meter") ctl.meterDir = c.meterDir ?? "Up";
        if (c.full === "repeat") {
          if (!c.repeatCount || c.repeatCount < 2) fail(where, 'a "repeat" control needs repeatCount >= 2');
          ctl.repeatCount = c.repeatCount;
        }
        return ctl;
      }
      const ctl2 = new Control(c.widget ?? "slider", param, null, visible, c.overlay ?? (c.widget === "switch" ? "menu" : "knob"), c.polarity ?? "auto");
      for (const [key, val, set] of [["nameSize", c.nameSize, (n: number) => (ctl2.nameSize = n)], ["valueSize", c.valueSize, (n: number) => (ctl2.valueSize = n)]] as const) {
        if (val === undefined) continue;
        if (c.widget !== "knob" && c.widget !== "fader" && c.widget !== "slider") fail(where, `only knob, fader and slider controls take ${key}`);
        if (!Number.isInteger(val) || (val !== 0 && (val < 8 || val > 60))) fail(where, `${key} must be 0 (hide) or a whole number of pixels from 8 to 60`);
        set(val);
      }
      if (c.size !== undefined) {
        if (c.widget !== "knob") fail(where, "only knob controls take a size");
        if (!Number.isInteger(c.size) || c.size < 24 || c.size > 107) fail(where, "knob size must be a whole number of pixels from 24 to 107");
        ctl2.size = c.size;
      }
      if (c.strip) {
        if (c.widget !== "knob" && c.widget !== "fader") fail(where, "only knob and fader controls take a custom image strip");
        if (!(c.strip in customAssets)) fail(where, `image asset "${c.strip}" is not in the project`);
        ctl2.strip = c.strip;
      }
      return ctl2;
    }
    const page = new Page(ps.name || String(pi + 1), controls);
    if (ps.background) page.background = ps.background;
    if (ps.images) page.images = ps.images.map((im, k): PageImage => {
      const where = `page[${pi}].images[${k}]`;
      const out: PageImage = { asset: im.asset, x: im.x, y: im.y, w: im.w, h: im.h };
      if (im.when) out.visible = parseVisibleWhen(im.when, table, where);
      if (im.param) out.valuePic = table.lookup(im.param, where);
      return out;
    });
    if (ps.qlinks) page.qlinks = ps.qlinks;
    if (ps.qlinkBounds) page.qlinkBounds = ps.qlinkBounds;
    return page;
  });

  const usesKit = pages.some((pg) => pg.controls.some((c) => c.full === "button" || KIT_OR_FULL.has(c.widget)));
  const kit: KitInfo | null = usesKit ? { theme: "mpc-red", accent: null } : null;
  const kitAssets: KitAssets = kit ? resolveKitAssets(kit) : {};
  const tui = buildTui(pages, params, style, null, 127, kitAssets, customAssets);
  const qlinks = buildQlinks(pages, params);
  return { tui: dumpJson(tui) + "\n", qlinks: dumpJson(qlinks) + "\n", kit };
}
